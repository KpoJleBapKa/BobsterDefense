package ua.bobster.defence.ballistic;

/**
 * Фаза польоту балістичної ракети.
 * <p>
 * Від фази залежить швидкість руху й насиченість реактивного сліду: на старті ракета
 * йде майже вертикально й повільно, у середині — накатом, на фініші пікірує швидше за все.
 */
public enum MissileState {

    /** Відрив від установки: майже чиста вертикаль. */
    LAUNCH,
    /** Набір висоти з поступовим доворотом на ціль. */
    ASCENT,
    /** Верхня ділянка дуги, двигун працює впівсили. */
    BALLISTIC,
    /** Пікірування на ціль — найшвидша фаза. */
    DESCENT,
    /** Ракета досягла точки удару. */
    IMPACT,
    /** Ракета знищена в повітрі. */
    DESTROYED
}
